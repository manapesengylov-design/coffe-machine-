// это 1 задание на switch case
void main() {
  String token = "4";
  switch (token) {
    case "1":
      print("Эспрессо — 100 сом");
      break;
    case "2":
      print("Американо — 120 сом");
      break;
    case "3":
      print("Капучино — 180 сом");
      break;
    case "4":
      print("Латте — 200 сом");
      break;
    case "5":
      print("Горячий шоколад — 150 сом");
      break;
    case "6":
      print("Чай — 80 сом");
      print("Приятного чаепития!");
      break;
    default:
      print("Неверный жетон!");
  }
}
 
 

